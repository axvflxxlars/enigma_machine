/*
 * score.h — оцінка, наскільки текст схожий на англійську.   Відповідальний: B
 *
 * Більша оцінка = більш схоже на англійську. Брейкер тільки порівнює оцінки між собою.
 */
#ifndef SCORE_H
#define SCORE_H

/*
 * Індекс збігу (IoC): sum n_i * (n_i - 1) / (N * (N - 1)).
 * Англійський текст ≈ 0.066, випадкові літери ≈ 0.038.
 */
double score_ioc(const int *t, int len);

/*
 * Завантажити таблицю n-грам (n = 2 або 3) з файлу формату "TH 116997844"
 * (n-грама, пробіл, кількість). Зберігати log10(count / total);
 * для n-грам, яких немає у файлі, — невелике «підлогове» значення,
 * наприклад log10(0.01 / total).
 * Повертає 0 при успіху, -1 при помилці.
 */
int ngram_load(const char *path, int n);

/* Сума log-ймовірностей усіх біграм/триграм тексту. Вимагає ngram_load(…, 2 / 3). */
double score_bigram(const int *t, int len);
double score_trigram(const int *t, int len);

#endif
